export const CITIES: City[] = RAW.map(([name, country, lat, lng, rank, admin1]) => ({ name, country, lat, lng, rank, admin1 }));

export function findCity(text: string): City | undefined {
  // Prefer the most specific (highest rank number = smaller place) mention.
  const hits = CITIES.filter((c) => new RegExp(`\\b${c.name.replace(/[()]/g, "")}\\b`, "i").test(text));
  return hits.sort((a, b) => b.rank - a.rank)[0];
}

export function citiesGeoJSON(): GeoJSON.FeatureCollection<GeoJSON.Point> {
  return {
    type: "FeatureCollection",
    features: CITIES.filter((c) => !c.name.includes("(")).map((c) => ({
      type: "Feature",
      properties: { name: c.name, rank: c.rank },
      geometry: { type: "Point", coordinates: [c.lng, c.lat] },
    })),
  };
}
